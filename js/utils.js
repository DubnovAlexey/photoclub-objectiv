// Системная настройка "уменьшить анимацию" — читается один раз при
// загрузке модуля и переиспользуется всеми, кому нужно её учитывать.
export const prefersReducedMotion =
  window.matchMedia('(prefers-reduced-motion: reduce)').matches;

// Единый на весь сайт AudioContext (Web Audio API).
// Хранится в замыкании модуля (module-scoped переменная НЕ экспортируется
// напрямую) — наружу отдаётся только функция доступа к нему.
let audioCtx = null;

/**
 * Возвращает общий AudioContext, создавая его при первом обращении.
 * Браузеры разрешают запускать AudioContext только по жесту
 * пользователя, поэтому эта функция всегда вызывается из обработчика
 * клика, а не сама по себе при загрузке страницы.
 */
export function getAudioContext() {
  if (!audioCtx) {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
  }
  if (audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

const FACTS = [
  'Официальная валюта космопорта «Скромный Странник» — галактические кредиты и, при острой необходимости, качественный кофе.',
  'Экипаж «Ржавой Селёдки» утверждает, что скрежещущий звук на поворотах — это «характер корабля», а не повод для беспокойства.',
  'Туманность Вечного Понедельника наблюдается в одной и той же фазе последние три галактических года. Причина неизвестна.',
  'На борту «Вечного Комфорта» гравитацию можно настроить под любое настроение — кроме понедельничного.',
  'Гид Грх официально работает без скидок для студентов. Неофициально скидка есть всегда.',
  'ЭХО-9 умеет переводить с 4000+ языков, но так и не подобрал точный перевод слову «дедлайн» — говорит, оно того не стоит.',
  'Автостопщики на орбитальных маршрутах голосуют любым количеством больших пальцев, какое у них есть.',
  'Кристаллический лишайник Кси-4 растёт быстрее там, где его не ждут — чаще всего на обшивке старых кораблей.',
];

export function initSpaceSafariFacts() {
  const btn = document.getElementById('randomFactBtn');
  const output = document.getElementById('randomFactText');
  if (!btn || !output) return;

  let lastIndex = -1;
  btn.addEventListener('click', () => {
    let index;
    do { index = Math.floor(Math.random() * FACTS.length); } while (index === lastIndex && FACTS.length > 1);
    lastIndex = index;
    output.textContent = FACTS[index];
  });
}
